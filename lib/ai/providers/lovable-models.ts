export type LovableModelId = keyof typeof LOVABLE_MODELS;

export const LOVABLE_MODEL_KEYS = Object.keys(
  LOVABLE_MODELS,
) as LovableModelId[];

export const LOVABLE_MODEL_PREFIX = "lovable-";

export const LOVABLE_DEFAULT_CUTOFF = "April 2026";

export function isLovableModelId(value: string): value is LovableModelId {
  return Object.hasOwn(LOVABLE_MODELS, value);
}

export function isLovableModelKey(value: string): boolean {
  return (
    value.startsWith(LOVABLE_MODEL_PREFIX) &&
    value.length > LOVABLE_MODEL_PREFIX.length
  );
}

export function getLovableModelId(key: string): string {
  if (isLovableModelId(key)) return LOVABLE_MODELS[key].id;
  return key.startsWith(LOVABLE_MODEL_PREFIX)
    ? key.slice(LOVABLE_MODEL_PREFIX.length)
    : key;
}

export function toLovableModelKey(gatewayId: string): string {
  for (const [key, meta] of Object.entries(LOVABLE_MODELS)) {
    if (meta.id === gatewayId) return key;
  }
  return `${LOVABLE_MODEL_PREFIX}${gatewayId}`;
}

export function getLovableModelName(key: string): string {
  if (isLovableModelId(key)) return LOVABLE_MODELS[key].name;
  const gatewayId = getLovableModelId(key);
  const label =
    gatewayId
      .split("/")
      .pop()
      ?.split("-")
      .map((word) =>
        word ? word.charAt(0).toUpperCase() + word.slice(1) : word,
      )
      .join(" ") ?? gatewayId;
  return `${label} (Lovable)`;
}

export function lovableModelSupportsThinking(key: string): boolean {
  return isLovableModelId(key) ? LOVABLE_MODELS[key].supportsThinking : false;
}

export function lovableModelUsesResponsesApi(key: string): boolean {
  return isLovableModelId(key)
    ? (LOVABLE_MODELS[key] as any).useResponsesApi === true
    : false;
}
