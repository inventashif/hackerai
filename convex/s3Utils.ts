"use node";

import { v4 as uuidv4 } from "uuid";
import { promises as fs } from "node:fs";
import path from "node:path";
import { hasVMStorage, vmFileUrl } from "../lib/file-explorer/vm-storage";

/**
 * Base directory for local file storage on the VM sandbox.
 * Defaults to /upload. Overridable via LOCAL_STORAGE_DIR.
 */
function getLocalStorageDir(): string {
  if (process.env.LOCAL_STORAGE_DIR) {
    return process.env.LOCAL_STORAGE_DIR;
  }
  // Default to /upload for VM sandbox deployment
  return "/upload";
}

/**
 * Base URL of the deployed app (Vercel production URL).
 * Used to construct sandbox proxy URLs.
 */
function getAppBaseUrl(): string {
  return process.env.NEXT_PUBLIC_APP_URL || "http://localhost:3000";
}

/**
 * Matches keys generated by generateS3Key: users/{userId}/{timestamp}-{uuid}.{ext}
 * Strict validation prevents path traversal on the local filesystem.
 */
const LOCAL_STORAGE_KEY_PATTERN =
  /^users\/[A-Za-z0-9_.-]{1,128}\/\d{1,20}-[0-9a-fA-F-]{1,64}(\.[A-Za-z0-9]{1,20})?$/;

export function isLocalStorageKey(s3Key: string): boolean {
  return LOCAL_STORAGE_KEY_PATTERN.test(s3Key);
}

/**
 * Resolve an s3Key to a safe absolute path under the VM's /upload directory.
 * This path is used by the sandbox VM when reading/writing files.
 */
export function localStorageFilePath(s3Key: string): string {
  if (!isLocalStorageKey(s3Key)) {
    throw new Error(`Invalid storage key: ${s3Key}`);
  }
  return path.join(/* turbopackIgnore: true */ getLocalStorageDir(), s3Key);
}

/**
 * Generate unique S3 key with user prefix
 * Format: users/{userId}/{timestamp}-{uuid}.{ext}
 * Only uses file extension from fileName, UUID ensures uniqueness
 */
export function generateS3Key(userId: string, fileName: string): string {
  const timestamp = Date.now();
  const uuid = uuidv4().replace(/-/g, "").slice(0, 12);
  const extension = path.extname(fileName);
  const safeUserId = userId.replace(/[^A-Za-z0-9_.-]/g, "_");
  return `users/${safeUserId}/${timestamp}-${uuid}${extension}`;
}

const S3_USER_FILES_PREFIX = "users";

/**
 * Generate sandbox upload URL for a file.
 * The client PUTs to /api/sandbox/upload?path=/upload/<s3Key>
 * which proxies to the VM sandbox.
 */
export async function generateS3UploadUrl(
  fileName: string,
  contentType: string,
  userId: string,
  contentLength?: number,
): Promise<{ uploadUrl: string; s3Key: string }> {
  const s3Key = generateS3Key(userId, fileName);
  const sandboxPath = `/upload/${s3Key}`;
  const uploadUrl = hasVMStorage()
    ? vmFileUrl("write", sandboxPath, { size: contentLength })
    : `${getAppBaseUrl()}/api/sandbox/upload?path=${encodeURIComponent(sandboxPath)}`;
  return { uploadUrl, s3Key };
}

/**
 * Generate sandbox download URL for a file.
 * The client GETs /api/sandbox/file?path=/upload/<s3Key>
 * which proxies to the VM sandbox.
 */
export async function generateS3DownloadUrl(s3Key: string): Promise<string> {
  if (!isLocalStorageKey(s3Key)) throw new Error("Invalid storage key");
  const sandboxPath = `/upload/${s3Key}`;
  if (hasVMStorage()) return vmFileUrl("read", sandboxPath);
  return `${getAppBaseUrl()}/api/sandbox/file?path=${encodeURIComponent(sandboxPath)}`;
}

/**
 * Delete object from VM sandbox storage.
 */
export async function deleteS3Object(s3Key: string): Promise<void> {
  if (!isLocalStorageKey(s3Key)) {
    return;
  }
  if (hasVMStorage()) {
    const response = await fetch(vmFileUrl("delete", `/upload/${s3Key}`), {
      method: "DELETE",
    });
    if (!response.ok) throw new Error("Failed to delete VM file");
    return;
  }
  await fs.rm(localStorageFilePath(s3Key), { force: true });
}

/**
 * Get object size in bytes from VM sandbox storage.
 */
export async function getS3ObjectSizeBytes(s3Key: string): Promise<number> {
  if (!isLocalStorageKey(s3Key)) throw new Error("Invalid storage key");
  if (hasVMStorage()) {
    const response = await fetch(vmFileUrl("stat", `/upload/${s3Key}`), {
      method: "HEAD",
    });
    if (!response.ok) throw new Error("File not found in VM storage");
    const size = Number(response.headers.get("content-length"));
    if (
      !response.headers.has("content-length") ||
      !Number.isSafeInteger(size) ||
      size < 0
    )
      throw new Error("Invalid VM file metadata");
    return size;
  }
  const stat = await fs.stat(
    /* turbopackIgnore: true */ localStorageFilePath(s3Key),
  );
  return stat.size;
}

